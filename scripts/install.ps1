<#
.SYNOPSIS
  Install the TargetHub server on Windows with Docker Desktop (or any Docker Engine with the
  compose v2 plugin). Generates .env with random secrets and starts the stack.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\install.ps1 -Port 8000
.EXAMPLE
  .\scripts\install.ps1 -Image ghcr.io/omkar-motaghare/targethub:0.2.0 -Url http://lab-hub:8000

.NOTES
  An existing .env is reused as-is (re-running just restarts the stack); -Force regenerates
  secrets and keeps the old file as .env.bak. Agents (Raspberry Pi, Linux, Windows) are
  installed separately from Admin -> Agents in the web UI.
#>
[CmdletBinding()]
param(
    [string]$Project = 'targethub',
    [int]$Port = 8000,
    [string]$Bind = '0.0.0.0',
    [string]$Url = '',
    [string]$Domain = '',
    [string]$Image = '',
    [switch]$NoStart,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function Fail([string]$Message) {
    Write-Error "install.ps1: $Message" -ErrorAction Continue
    exit 1
}

$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root
$EnvFile = Join-Path $Root '.env'

if ($Project -notmatch '^[a-z0-9][a-z0-9_-]*$') { Fail '-Project must be lowercase letters, digits, - or _' }
if ($Port -lt 1 -or $Port -gt 65535) { Fail '-Port must be 1-65535' }

$docker = Get-Command docker -ErrorAction SilentlyContinue
if (-not $docker) { Fail 'docker is not installed (install Docker Desktop and start it)' }
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Fail 'the docker compose plugin (v2) is required' }

function New-RandomHex([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

function Write-EnvFile([string[]]$Lines) {
    # LF line endings and no BOM so docker compose parses it identically on every platform.
    $text = ($Lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($EnvFile, $text, (New-Object System.Text.UTF8Encoding($false)))
    if ($env:OS -eq 'Windows_NT') {
        # Only the current user, Administrators and SYSTEM may read the secrets.
        & icacls $EnvFile /inheritance:r /grant:r "$($env:USERNAME):(F)" '*S-1-5-32-544:(F)' '*S-1-5-18:(F)' *> $null
    } else {
        & chmod 600 $EnvFile
    }
}

function Get-EnvValue([string]$Name) {
    if (-not (Test-Path $EnvFile)) { return '' }
    $line = Get-Content $EnvFile | Where-Object { $_ -match "^$([regex]::Escape($Name))=" } | Select-Object -Last 1
    if ($line) { return $line.Substring($Name.Length + 1).Trim() }
    return ''
}

if ((Test-Path $EnvFile) -and -not $Force) {
    Write-Host 'Reusing existing .env (use -Force to regenerate).'
} else {
    if (Test-Path $EnvFile) {
        Copy-Item $EnvFile "$EnvFile.bak" -Force
        Write-Host 'Existing .env saved as .env.bak'
    }
    if ($Domain) {
        if (-not $Url) { $Url = "https://$Domain" }
        $Bind = '127.0.0.1'
    } elseif (-not $Url) {
        $hostName = if ($Bind -ne '0.0.0.0') { $Bind } else { [System.Net.Dns]::GetHostName() }
        $Url = "http://${hostName}:$Port"
    }
    $lines = @(
        "# Generated by scripts/install.ps1 on $((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')). Keep private.",
        "COMPOSE_PROJECT_NAME=$Project",
        "TARGETHUB_BIND=$Bind",
        "TARGETHUB_PORT=$Port"
    )
    if ($Domain) {
        # compose splits COMPOSE_FILE on the OS path separator (';' on Windows).
        $sep = [System.IO.Path]::PathSeparator
        $lines += "COMPOSE_FILE=docker-compose.yml${sep}docker-compose.tls.yml"
        $lines += "TARGETHUB_DOMAIN=$Domain"
    }
    $lines += @(
        "TARGETHUB_PUBLIC_URL=$Url",
        "SECRET_KEY=$(New-RandomHex 32)",
        "POSTGRES_PASSWORD=$(New-RandomHex 24)",
        "ADMIN_BOOTSTRAP_TOKEN=$(New-RandomHex 16)",
        "METRICS_TOKEN=$(New-RandomHex 16)",
        'LOG_LEVEL=INFO',
        'API_WORKERS=2'
    )
    if ($Image) { $lines += "TARGETHUB_IMAGE=$Image" }
    Write-EnvFile $lines
    Write-Host 'Wrote .env with freshly generated secrets.'
}

if ($Image -and (Get-EnvValue 'TARGETHUB_IMAGE') -ne $Image) {
    $kept = @(Get-Content $EnvFile | Where-Object { $_ -notmatch '^TARGETHUB_IMAGE=' })
    Write-EnvFile ($kept + "TARGETHUB_IMAGE=$Image")
}
$Image = Get-EnvValue 'TARGETHUB_IMAGE'

if ($NoStart) {
    Write-Host 'Skipping start (-NoStart). Run: docker compose up -d --build --wait'
    exit 0
}

if ($Image -and $Image -ne 'targethub:local') {
    Write-Host "Pulling $Image and starting TargetHub..."
    & docker compose pull
    if ($LASTEXITCODE -ne 0) { Fail "could not pull $Image (check the tag and registry access)" }
    $upArgs = @('--no-build')
} else {
    Write-Host 'Building and starting TargetHub (first build takes a few minutes)...'
    $upArgs = @('--build')
}
& docker compose up -d @upArgs --wait --wait-timeout 300
if ($LASTEXITCODE -ne 0) {
    & docker compose ps
    & docker compose logs --tail=60
    Fail 'stack did not become healthy'
}

$publicUrl = Get-EnvValue 'TARGETHUB_PUBLIC_URL'
Write-Host ''
Write-Host "TargetHub is running: $publicUrl/app"
$setupRequired = $false
try {
    $status = Invoke-RestMethod -UseBasicParsing -TimeoutSec 5 "http://127.0.0.1:$(Get-EnvValue 'TARGETHUB_PORT')/api/v1/auth/setup-status"
    $setupRequired = [bool]$status.setup_required
} catch { $setupRequired = [bool]$Domain }
if ($setupRequired) {
    Write-Host 'First run: open the URL above and create the admin account with this bootstrap token:'
    Write-Host "  $(Get-EnvValue 'ADMIN_BOOTSTRAP_TOKEN')"
}
Write-Host "Secrets live in $EnvFile (readable by you and Administrators only)."
Write-Host 'Back up the database: docker compose exec db pg_dump -U targethub targethub > backup.sql'
