#!/usr/bin/env bash
# Install TargetHub with Docker Compose: generates .env with random secrets and starts the stack.
#
# Usage: scripts/install.sh [options]
#   --project NAME   compose project name / volume prefix      (default: targethub)
#   --port PORT      host port for the web UI + API            (default: 8000)
#   --bind ADDR      host address to publish on                (default: 0.0.0.0)
#   --url URL        public URL users and agents will use      (default: http://<host>:<port>)
#   --domain NAME    enable the Caddy TLS overlay for NAME (ports 80/443, API not published)
#   --image REF      run a published image (e.g. ghcr.io/omkar-motaghare/targethub:0.2.0)
#                    instead of building from source
#   --no-start       write .env only
#   --force          overwrite an existing .env (secrets are regenerated; the old file is kept as .env.bak)
# An existing .env is reused as-is: re-running the script just (re)starts the stack.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PROJECT=targethub
PORT=8000
BIND=0.0.0.0
URL=""
DOMAIN=""
IMAGE=""
START=1
FORCE=0

usage() { sed -n '2,15p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }
die() { echo "install.sh: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --project) PROJECT="${2:?--project needs a value}"; shift 2 ;;
    --port) PORT="${2:?--port needs a value}"; shift 2 ;;
    --bind) BIND="${2:?--bind needs a value}"; shift 2 ;;
    --url) URL="${2:?--url needs a value}"; shift 2 ;;
    --domain) DOMAIN="${2:?--domain needs a value}"; shift 2 ;;
    --image) IMAGE="${2:?--image needs a value}"; shift 2 ;;
    --no-start) START=0; shift ;;
    --force) FORCE=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) usage >&2; die "unknown option: $1" ;;
  esac
done

[[ "$PROJECT" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || die "--project must be lowercase letters, digits, - or _"
[[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || die "--port must be 1-65535"

command -v docker >/dev/null || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "the docker compose plugin (v2) is required"

random_hex() {
  local bytes="$1"
  if command -v openssl >/dev/null; then
    openssl rand -hex "$bytes"
  else
    head -c "$bytes" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

if [ -f .env ] && [ "$FORCE" -eq 0 ]; then
  echo "Reusing existing .env (use --force to regenerate)."
else
  if [ -f .env ]; then
    cp -p .env .env.bak
    echo "Existing .env saved as .env.bak"
  fi
  if [ -n "$DOMAIN" ]; then
    [ -n "$URL" ] || URL="https://$DOMAIN"
    BIND=127.0.0.1
  elif [ -z "$URL" ]; then
    HOST_NAME="$(hostname -I 2>/dev/null | awk '{print $1}')"
    [ "$BIND" = "0.0.0.0" ] || HOST_NAME="$BIND"
    URL="http://${HOST_NAME:-localhost}:$PORT"
  fi
  umask 077
  {
    echo "# Generated by scripts/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep private."
    echo "COMPOSE_PROJECT_NAME=$PROJECT"
    echo "TARGETHUB_BIND=$BIND"
    echo "TARGETHUB_PORT=$PORT"
    if [ -n "$DOMAIN" ]; then
      echo "COMPOSE_FILE=docker-compose.yml:docker-compose.tls.yml"
      echo "TARGETHUB_DOMAIN=$DOMAIN"
    fi
    echo "TARGETHUB_PUBLIC_URL=$URL"
    echo "SECRET_KEY=$(random_hex 32)"
    echo "POSTGRES_PASSWORD=$(random_hex 24)"
    echo "ADMIN_BOOTSTRAP_TOKEN=$(random_hex 16)"
    echo "METRICS_TOKEN=$(random_hex 16)"
    echo "LOG_LEVEL=INFO"
    echo "API_WORKERS=2"
    [ -z "$IMAGE" ] || echo "TARGETHUB_IMAGE=$IMAGE"
  } >.env
  chmod 600 .env
  echo "Wrote .env with freshly generated secrets."
fi

env_value() { { grep -E "^$1=" .env || true; } | tail -n1 | cut -d= -f2-; }

if [ -n "$IMAGE" ] && [ "$(env_value TARGETHUB_IMAGE)" != "$IMAGE" ]; then
  # Reused .env: record the requested image without touching the secrets.
  grep -v '^TARGETHUB_IMAGE=' .env >.env.tmp && echo "TARGETHUB_IMAGE=$IMAGE" >>.env.tmp
  chmod 600 .env.tmp && mv .env.tmp .env
fi
IMAGE="$(env_value TARGETHUB_IMAGE)"

if [ "$START" -eq 0 ]; then
  echo "Skipping start (--no-start). Run: docker compose up -d --build --wait"
  exit 0
fi

if [ -n "$IMAGE" ] && [ "$IMAGE" != "targethub:local" ]; then
  echo "Pulling $IMAGE and starting TargetHub..."
  docker compose pull >&2 || die "could not pull $IMAGE (check the tag and registry access)"
  UP_ARGS=(--no-build)
else
  echo "Building and starting TargetHub (first build takes a few minutes)..."
  UP_ARGS=(--build)
fi
docker compose up -d "${UP_ARGS[@]}" --wait --wait-timeout 300 || {
  docker compose ps >&2 || true
  docker compose logs --tail=60 >&2 || true
  die "stack did not become healthy"
}

echo
echo "TargetHub is running: $(env_value TARGETHUB_PUBLIC_URL)/app"
if [ "$(curl -fsS "http://127.0.0.1:$(env_value TARGETHUB_PORT)/api/v1/auth/setup-status" 2>/dev/null | grep -c '"setup_required":true')" -eq 1 ] \
  || [ -n "$DOMAIN" ]; then
  echo "First run: open the URL above and create the admin account with this bootstrap token:"
  echo "  $(env_value ADMIN_BOOTSTRAP_TOKEN)"
fi
echo "Secrets live in $ROOT/.env (mode 600). Back up the database with scripts/backup.sh."
